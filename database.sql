-- ইসলামিক কিতাব ঘর — Supabase database starter schema
create table if not exists public.books (
  id bigint generated by default as identity primary key,
  title text not null,
  author text not null,
  category text not null,
  description text default '',
  cover_url text default '',
  pdf_url text default '',
  created_at timestamptz not null default now()
);

create table if not exists public.duas (
  id bigint generated by default as identity primary key,
  title text not null,
  arabic text default '',
  pronunciation text default '',
  meaning text default '',
  reference text default '',
  created_at timestamptz not null default now()
);

create table if not exists public.gallery (
  id bigint generated by default as identity primary key,
  title text not null,
  image_url text not null,
  created_at timestamptz not null default now()
);

-- প্রথম ধাপে public reading-এর জন্য RLS চালু করুন।
alter table public.books enable row level security;
alter table public.duas enable row level security;
alter table public.gallery enable row level security;

-- Public visitors read করতে পারবে।
create policy "public can read books"
on public.books for select
to anon, authenticated
using (true);

create policy "public can read duas"
on public.duas for select
to anon, authenticated
using (true);

create policy "public can read gallery"
on public.gallery for select
to anon, authenticated
using (true);

-- Admin write policy এখানে ইচ্ছাকৃতভাবে দেওয়া হয়নি।
-- Production admin-এর জন্য Supabase Auth + authenticated role + RLS policy
